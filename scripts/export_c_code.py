"""Generate the acados solver C code and the track table for the ROS 2 package.

    python scripts/export_c_code.py [--out ros2/vehicle_nmpc_ros/generated]

Writes
  <out>/c_generated_code/   acados solver "vehicle_nmpc" (C sources + CMakeLists)
  <out>/track.csv           s, kappa (closed track, for the simulator node)
  <out>/model_params.yaml   vehicle, tyre and horizon values the C++ code checks against
The ROS 2 package compiles the generated sources directly; no Python is needed at run time.
"""
from __future__ import annotations

import argparse
import json
import sys
import warnings
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
warnings.filterwarnings("ignore")

from vnmpc.nmpc import NMPCConfig, build_ocp  # noqa: E402
from vnmpc.params import Vehicle  # noqa: E402
from vnmpc.track import Track  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "ros2" / "vehicle_nmpc_ros" / "generated"))
    a = ap.parse_args()
    out = Path(a.out).resolve()
    out.mkdir(parents=True, exist_ok=True)

    from acados_template import AcadosOcpSolver

    veh, tr = Vehicle(), Track.default()
    cfg = NMPCConfig(name="vehicle_nmpc")
    ocp = build_ocp(veh, tr, cfg)
    ocp.name = "vehicle_nmpc"  # stable C symbol prefix (default appends a hash)
    ocp.code_export_directory = str(out / "c_generated_code")
    ocp.json_file = str(out / "c_generated_code" / "vehicle_nmpc.json")
    AcadosOcpSolver.generate(ocp, verbose=False)

    np.savetxt(out / "track.csv", np.c_[tr.s, tr.kappa], delimiter=",",
               header=f"length={tr.length:.6f},half_width={tr.half_width}", comments="# ",
               fmt="%.9g")
    t = veh.tyre
    params = dict(m=veh.m, Iz=veh.Iz, lf=veh.lf, lr=veh.lr, B=t.B, C=t.C, D=t.D,
                  delta_max=veh.delta_max, delta_rate_max=veh.delta_rate_max,
                  ax_min=veh.ax_min, ax_max=veh.ax_max, N=cfg.N, dt0=cfg.dt0,
                  track_length=tr.length, half_width=tr.half_width)
    (out / "model_params.yaml").write_text(
        "# generated by scripts/export_c_code.py\n"
        + "\n".join(f"{k}: {json.dumps(v)}" for k, v in params.items()) + "\n")
    print(f"exported to {out}")


if __name__ == "__main__":
    main()
